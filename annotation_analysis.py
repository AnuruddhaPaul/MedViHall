def ci(arr, lo=2.5, hi=97.5):
    arr = np.asarray(arr, float)
    arr = arr[~np.isnan(arr)]
    if len(arr) == 0:
        return (np.nan, np.nan)
    return (float(np.percentile(arr, lo)), float(np.percentile(arr, hi)))


