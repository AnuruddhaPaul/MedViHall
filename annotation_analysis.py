def icc(X):
    n, k = X.shape
    gm = X.mean()
    rm, cm = X.mean(1), X.mean(0)
    ssr, ssc = k * ((rm - gm) ** 2).sum(), n * ((cm - gm) ** 2).sum()
    sse = ((X - gm) ** 2).sum() - ssr - ssc
    msr, msc, mse = ssr / (n - 1), ssc / (k - 1), sse / ((n - 1) * (k - 1))
    i1 = (msr - mse) / (msr + (k - 1) * mse + k * (msc - mse) / n)
    ik = (msr - mse) / (msr + (msc - mse) / n)
    return i1, ik


def kripp_interval(X):
    n, k = X.shape
    Nn = n * k
    su = (2 * k * (X ** 2).sum(1) - 2 * X.sum(1) ** 2).sum()
    do = su / (Nn * (k - 1))
    v = X.ravel()
    de = (2 * Nn * (v ** 2).sum() - 2 * v.sum() ** 2) / (Nn * (Nn - 1))
    return 1 - do / de if de > 0 else np.nan


def binned(x):
    return np.minimum(np.floor(x / 0.5 + 1e-9).astype(int), 10)


def qwk(a, b, K=11):
    O = np.bincount(a * K + b, minlength=K * K).reshape(K, K).astype(float)
    n = O.sum()
    E = np.outer(O.sum(1), O.sum(0)) / n
    Wm = (np.arange(K)[:, None] - np.arange(K)[None, :]) ** 2
    den = (Wm * E).sum()
    return 1 - (Wm * O).sum() / den if den > 0 else np.nan


def mean_pair_qwk(X):
    Bn = binned(X)
    return float(np.nanmean([qwk(Bn[:, i], Bn[:, j]) for i, j in itertools.combinations(range(X.shape[1]), 2)]))


def cohen(a, b):
    po = (a == b).mean()
    pa, pb = a.mean(), b.mean()
    pe = pa * pb + (1 - pa) * (1 - pb)
    return (po - pe) / (1 - pe) if pe < 1 else np.nan


def fleiss(Y):
    n, k = Y.shape
    ni = Y.sum(1)
    Pi = (ni * (ni - 1) + (k - ni) * (k - ni - 1)) / (k * (k - 1))
    p = Y.mean()
    pe = p * p + (1 - p) ** 2
    return (Pi.mean() - pe) / (1 - pe) if pe < 1 else np.nan


def mean_pair_kappa(Y):
    return float(np.nanmean([cohen(Y[:, i], Y[:, j]) for i, j in itertools.combinations(range(Y.shape[1]), 2)]))


def mean_pair_agree(Y):
    return float(np.mean([(Y[:, i] == Y[:, j]).mean() for i, j in itertools.combinations(range(Y.shape[1]), 2)]))


def boot_stat(fn, items, idxmat):
    vals = np.array([fn(items[ix]) for ix in idxmat])
    return ci(vals)


