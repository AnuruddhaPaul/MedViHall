def smhr_sets(Ssum):
    """Ssum (..., models, 8) -> SMHR (..., K, models)."""
    num = np.einsum('...mc,kc->...km', Ssum[..., :7], Wm)
    return num / np.maximum(Ssum[..., 7][..., None, :], 1e-9)


def rank_of(x):
    return np.argsort(np.argsort(x, axis=-1), axis=-1)


def paradox_flags(Sall, Smods):
    """Sall: (R, models, 8) aggregate; Smods: dict mod -> (R, models, 8). Returns (rank_ok, sri_ok, rho_vs_assumed)."""
    smh = smhr_sets(Sall)                                          # (R,K,M)
    rk = rank_of(smh)
    n_m = len(models12)
    med_ok = (rk[..., medical] >= n_m - 3).all(-1)                  # three medical models occupy the three worst ranks
    sri_ok = np.ones(med_ok.shape, bool)
    for m in MODS:
        sm = smhr_sets(Smods[m])                                   # (R,K,M)
        best_gen = np.min(np.where(medical[None, None, :], np.inf, sm), axis=-1)
        sri_ok &= (sm[..., medical] / best_gen[..., None] > 1).all(-1)
    a = smh[:, :1, :]
    ra = rank_of(a)
    rho = np.empty(med_ok.shape)
    for k in range(rho.shape[1]):
        x, y = ra[:, 0, :].astype(float), rk[:, k, :].astype(float)
        xc, yc = x - x.mean(1, keepdims=True), y - y.mean(1, keepdims=True)
        rho[:, k] = (xc * yc).sum(1) / np.sqrt((xc ** 2).sum(1) * (yc ** 2).sum(1))
    return med_ok, sri_ok, rho, smh


